CREATE TABLE IF NOT EXISTS agencies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  short_name VARCHAR(64) NOT NULL,
  description VARCHAR(255) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE categories ADD COLUMN IF NOT EXISTS agency_id INT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS agency_id INT NULL;

ALTER TABLE reports MODIFY COLUMN user_id INT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS agency_id INT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS kecamatan VARCHAR(100) NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS desa VARCHAR(100) NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS is_anonymous TINYINT(1) NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS emergency_contacts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  agency_name VARCHAR(120) NOT NULL,
  category VARCHAR(64) NOT NULL,
  phone_number VARCHAR(32) NOT NULL,
  whatsapp_number VARCHAR(32) NULL,
  address VARCHAR(255) NULL,
  is_24_hours TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 0,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rate_limits (
  key_hash VARCHAR(64) PRIMARY KEY,
  action VARCHAR(32) NOT NULL,
  hits INT NOT NULL DEFAULT 1,
  reset_at TIMESTAMP NOT NULL,
  INDEX idx_rate_limits_reset (reset_at)
);
